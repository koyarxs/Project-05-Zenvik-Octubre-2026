import { test, expect, type Page } from '@playwright/test';
test.skip(process.env.E2E_INCIDENTS !== '1', 'Fixture aislada de incidencias');
const business = process.env.E2E_BUSINESS_A!;
const other = process.env.E2E_BUSINESS_B!;
const base = `/api/v1/businesses/${business}/attendance`;
async function login(page: Page, username: string) {
  await page.goto('/iniciar-sesion');
  await page.getByLabel('Nombre de usuario', { exact: true }).fill(username);
  await page.getByLabel('Contraseña', { exact: true }).fill('Browser-test!pass-9274');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await expect(page).toHaveURL(/\/app$/);
}
const mutation = (page: Page, path: string) => page.waitForResponse(response => response.request().method() === 'POST' && response.url().includes(path) && (response.status() < 300 || response.status() >= 400));

test('regularización completa, notificaciones, originales intactos y aislamiento a 320 px', async ({ page, browser }) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width: 320, height: 740 });
  await login(page, 'incident_worker');
  await page.goto(`/app/${business}/asistencia`);
  await expect(page.getByRole('heading', { name: 'Mi asistencia', exact: true })).toBeVisible();
  const original = await (await page.request.get(`${base}/receipts/${process.env.E2E_INCIDENT_EVENT}/`)).json();
  await page.goto(`/app/${business}/incidencias`);
  await page.getByRole('button', { name: 'Nueva solicitud', exact: true }).click();
  await page.getByLabel('Fecha laboral', { exact: true }).fill(process.env.E2E_INCIDENT_DATE!);
  await page.getByLabel('Jornada relacionada', { exact: true }).selectOption(process.env.E2E_INCIDENT_SESSION!);
  await page.getByLabel('Categoría de incidencia', { exact: true }).selectOption('MISSING_CLOCK_OUT');
  await page.getByLabel('Fecha y hora declarada (America/Santiago)', { exact: true }).fill(process.env.E2E_DECLARED_TIME!);
  await page.getByLabel('Motivo', { exact: true }).fill('Olvidé registrar la salida al finalizar mi trabajo.');
  await page.screenshot({ path:'test-results/stage14-worker-form-320.png', fullPage:false });
  const created = mutation(page, '/incidents');
  await page.getByRole('button', { name:'Enviar solicitud', exact:true }).click();
  const createdResponse = await created; expect(createdResponse.status()).toBe(201);
  const incident = await createdResponse.json();
  await expect(page.getByRole('dialog')).toContainText('Declaración del trabajador');
  await expect(page.getByRole('dialog')).toContainText('Pendiente');
  expect((await page.request.get(`${base}/audit/`)).status()).toBe(403);
  const adminContext = await browser.newContext(); const admin = await adminContext.newPage();
  await login(admin, 'incident_owner');
  await admin.goto(`/app/${business}/notificaciones`);
  await expect(admin.getByText('Nueva solicitud pendiente', { exact:true })).toBeVisible();
  await admin.getByRole('link', {name:'Ver recurso',exact:true}).click();
  await expect(admin.getByRole('dialog')).toContainText(process.env.E2E_INCIDENT_EVENT!);
  await admin.getByLabel('Decisión de incidencia', {exact:true}).selectOption('IN_REVIEW');
  await admin.getByLabel('Justificación de la decisión', {exact:true}).fill('Se revisa la evidencia original y el horario declarado.');
  const review = mutation(admin, '/transition'); await admin.getByRole('button', {name:'Confirmar decisión'}).click(); expect((await review).status()).toBe(201);
  await expect(admin.getByRole('dialog')).toContainText('Pendiente → En revisión');
  await admin.getByLabel('Decisión de incidencia', {exact:true}).selectOption('APPROVED');
  await admin.getByLabel('Justificación de la decisión', {exact:true}).fill('Se aprueba el ajuste operativo tras revisar los antecedentes.');
  const approval = mutation(admin, '/transition'); await admin.getByRole('button', {name:'Confirmar decisión'}).click(); expect((await approval).status()).toBe(201);
  await expect(admin.getByRole('dialog')).toContainText('En revisión → Aprobada');
  await admin.getByText('Ajuste operativo aprobado', {exact:true}).scrollIntoViewIfNeeded();
  await admin.screenshot({ path:'test-results/stage14-approved-detail.png', fullPage:false });
  await admin.keyboard.press('Escape');
  await admin.getByRole('button', {name:'Ajustes operativos',exact:true}).click();
  await expect(admin.getByText('Ajuste operativo aprobado', {exact:true})).toBeVisible();
  await admin.screenshot({ path:'test-results/stage14-corrections-desktop.png', fullPage:true });
  await admin.getByRole('button', {name:'Auditoría',exact:true}).click();
  await expect(admin.getByRole('heading', {name:'OPERATIONAL_CORRECTION',exact:true})).toBeVisible();
  await admin.screenshot({ path:'test-results/stage14-audit-desktop.png', fullPage:true });
  await page.keyboard.press('Escape');
  await page.goto(`/app/${business}/notificaciones`);
  const approvedNotice = page.locator('article').filter({hasText:'Solicitud aprobada'});
  await expect(approvedNotice).toBeVisible();
  await approvedNotice.getByRole('button', {name:'Marcar como leída'}).click();
  await expect(page.locator('article').filter({hasText:'Solicitud aprobada'})).toContainText('Leída');
  await page.screenshot({ path:'test-results/stage14-notifications-320.png', fullPage:true });
  await page.locator('article').filter({hasText:'Solicitud aprobada'}).getByRole('link', {name:'Ver recurso'}).click();
  await expect(page.getByRole('dialog')).toContainText('En revisión → Aprobada');
  await expect(page.getByRole('button', {name:'Confirmar decisión'})).toHaveCount(0);
  expect(await (await page.request.get(`${base}/receipts/${process.env.E2E_INCIDENT_EVENT}/`)).json()).toEqual(original);
  expect((await page.request.get(`/api/v1/businesses/${other}/attendance/incidents/${incident.id}/`)).status()).toBe(404);
  expect((await admin.request.get(`/api/v1/businesses/${other}/attendance/incidents/${incident.id}/`)).status()).toBe(404);
  await page.keyboard.press('Escape');
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await admin.goto(`/app/${other}/incidencias`);
  await expect(admin.getByText('No hay solicitudes para estos filtros.')).toBeVisible();
  await admin.goto(`/app/${business}/incidencias`);
  await admin.getByLabel('Estado de solicitud', {exact:true}).selectOption('REJECTED');
  await expect(admin.getByText('No hay solicitudes para estos filtros.')).toBeVisible();
  await admin.route(url => /\/attendance\/incidents\/?$/.test(url.pathname), route => route.abort());
  await admin.getByRole('button', {name:'Actualizar incidencias'}).click();
  await expect(admin.getByRole('button', {name:'Volver a intentar',exact:true})).toBeVisible();
  await adminContext.close();
});
