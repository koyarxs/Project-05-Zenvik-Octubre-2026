import { test, expect } from '@playwright/test';
test.skip(!process.env.E2E_PLANNING, 'Uses isolated planning fixtures');
const business = process.env.E2E_BUSINESS_A!;
const employee = process.env.E2E_COLLEAGUE!;

test('planificación mensual, colación, duplicación, copia, reglas e historial', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto('/iniciar-sesion');
  await page.getByLabel('Nombre de usuario', { exact: true }).fill('owner_planning');
  await page.getByLabel('Contraseña', { exact: true }).fill('Browser-test!pass-9274');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await expect(page).toHaveURL(/\/app$/);
  await page.goto(`/app/${business}/turnos`);
  await page.getByLabel('Semana que incluye').fill('2026-10-26');
  await page.getByRole('button', { name: 'Mes', exact: true }).click();
  await expect(page.getByLabel('Calendario mensual')).toBeVisible();
  await page.getByRole('button', { name: 'Mes siguiente', exact: true }).click();
  await expect(page.getByLabel('Semana que incluye')).toHaveValue('2026-11-01');
  await page.getByRole('button', { name: 'Mes anterior', exact: true }).click();
  await expect(page.getByLabel('Semana que incluye')).toHaveValue('2026-10-01');

  await page.getByRole('button', { name: 'Crear turno el 2026-10-26', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Trabajador', { exact: true }).selectOption(employee);
  await page.getByLabel('Colación o descanso (minutos)').fill('30');
  await page.getByLabel('Incluir la colación').uncheck();
  await page.getByLabel('Observaciones (opcional)').fill('Preparar cierre');
  await page.getByRole('dialog').getByRole('button', { name: 'Crear turno', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: /Planificación Test.*09:00.*17:00/ }).click();
  await expect(page.getByRole('dialog')).toContainText('Tiempo programado: 450 min');
  await page.getByText('Historial del turno', { exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Creación');
  await page.getByRole('button', { name: 'Duplicar turno', exact: true }).click();
  await page.getByLabel('Inicio del turno', { exact: true }).fill('2026-10-27T09:00');
  await page.getByLabel('Término del turno', { exact: true }).fill('2026-10-27T17:00');
  await page.getByRole('dialog').getByRole('button', { name: 'Crear turno', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button', { name: /Planificación Test.*09:00.*17:00/ })).toHaveCount(2);
  await page.getByLabel('Calendario mensual').screenshot({ animations: 'disabled', path: 'test-results/planning-month-desktop.png' });
  await page.getByLabel('Estado del turno').selectOption('CANCELLED');
  await expect(page.getByRole('button', { name: /Planificación Test.*09:00.*17:00/ })).toHaveCount(0);
  await page.getByLabel('Estado del turno').selectOption('ALL');
  await expect(page.getByRole('button', { name: /Planificación Test.*09:00.*17:00/ })).toHaveCount(2);
  await page.getByRole('button', { name: 'Semana', exact: true }).click();
  await page.getByLabel('Semana que incluye').fill('2026-10-26');
  await page.getByRole('button', { name: 'Copiar semana', exact: true }).click();
  await page.getByLabel('Semana de destino').fill('2026-11-02');
  await page.getByRole('button', { name: 'Confirmar copia', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Semana siguiente', exact: true }).click();
  await expect(page.getByRole('button', { name: /Planificación Test.*09:00.*17:00/ })).toHaveCount(2);
  await page.getByRole('button', { name: 'Reglas de planificación', exact: true }).click();
  await page.getByLabel('Duración máxima por turno (minutos)').fill('300');
  await page.getByRole('button', { name: 'Guardar reglas', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: /Planificación Test.*09:00.*17:00/ }).first().click();
  await page.getByRole('button', { name: 'Duplicar turno', exact: true }).click();
  await page.getByLabel('Inicio del turno', { exact: true }).fill('2026-11-04T09:00');
  await page.getByLabel('Término del turno', { exact: true }).fill('2026-11-04T17:00');
  await page.getByRole('dialog').getByRole('button', { name: 'Crear turno', exact: true }).click();
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('duración máxima');
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 768, height: 1024 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ animations: 'disabled', path: 'test-results/planning-tablet.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Mes', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(page.getByRole('button', { name: /Planificación Test.*09:00.*17:00/ })).toHaveCount(2);
  await page.getByRole('button', { name: /Planificación Test.*09:00.*17:00/ }).first().scrollIntoViewIfNeeded();
  await page.screenshot({ animations: 'disabled', path: 'test-results/planning-month-mobile.png', fullPage: true });
});
