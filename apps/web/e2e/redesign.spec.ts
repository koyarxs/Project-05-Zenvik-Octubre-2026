import { test, expect, type Page } from '@playwright/test';
const business = process.env.E2E_BUSINESS_A!;
async function login(page: Page, user: string) {
  await page.goto('/iniciar-sesion');
  await page.getByLabel('Nombre de usuario', { exact: true }).fill(user);
  await page.getByLabel('Contraseña', { exact: true }).fill('Browser-test!pass-9274');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await expect(page).toHaveURL(/\/app$/);
  await page.goto(`/app/${business}`);
  await expect(page.getByRole('heading', { name: 'Negocio A de prueba', exact: true })).toBeVisible();
}
test('centro de operaciones, acciones rápidas y navegación contraíble', async ({ page }) => {
  await page.goto('/iniciar-sesion');
  await page.getByLabel('Contraseña', { exact: true }).fill('test');
  await page.getByRole('button', { name: 'Mostrar contraseña' }).click();
  await expect(page.getByLabel('Contraseña', { exact: true })).toHaveAttribute('type', 'text');
  await page.getByRole('button', { name: 'Ocultar contraseña' }).click();
  await page.getByLabel('Contraseña', { exact: true }).clear();
  await page.screenshot({ path: 'test-results/v2-login.png', fullPage: true });
  await login(page, 'owner_design');
  const today = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Turnos de hoy', exact: true }) });
  await expect(today.getByText('Valentina Rojas', { exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Necesitan tu atención', exact: true })).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/v2-dashboard.png', fullPage: true });
  const sidebar = page.getByRole('complementary', { name: 'Navegación principal' });
  await page.getByRole('button', { name: 'Contraer menú lateral' }).click();
  await expect.poll(async () => (await sidebar.boundingBox())?.width).toBe(84);
  await page.getByRole('button', { name: 'Expandir menú lateral' }).click();
  await expect(page.getByLabel('Negocio activo')).toBeVisible();
  await page.getByRole('link', { name: 'Crear turno', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Nuevo turno');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Agenda', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Agenda', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('link', { name: 'Configuración', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Tu espacio de trabajo' })).toBeVisible();
  await page.getByRole('button', { name: 'Actualizar información', exact: true }).click();
  await expect(page.getByText('Información actualizada', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Cerrar aviso', exact: true }).click();
});
test('directorio completo, perfil relacionado y desactivación con confirmación', async ({ page }) => {
  await login(page, 'owner_directory');
  await page.goto(`/app/${business}/trabajadores`);
  await expect(page.getByRole('link', { name: 'Ver ficha de Valentina Rojas', exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/v2-directory.png', fullPage: true });
  await page.getByLabel('Buscar trabajadores', { exact: true }).fill('Valentina');
  await expect(page.getByRole('link', { name: 'Ver ficha de Valentina Rojas', exact: true })).toBeVisible();
  await expect(page.getByText('Otra ficha De prueba', { exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: 'Ver ficha de Valentina Rojas', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Próximos turnos', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Solicitudes relacionadas', exact: true })).toBeVisible();
  await expect(page.getByRole('status').filter({ hasText: 'Consultando' })).toHaveCount(0);
  await page.screenshot({ path: 'test-results/v2-profile.png', fullPage: true });
  await page.goto(`/app/${business}/trabajadores`);
  await page.getByLabel('Buscar trabajadores', { exact: true }).fill('Mateo');
  await page.getByRole('link', { name: 'Ver ficha de Mateo Fuentes', exact: true }).click();
  await page.getByRole('link', { name: 'Editar trabajador', exact: true }).click();
  await page.getByLabel('Trabajador activo').uncheck();
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('¿Desactivar este trabajador?');
  await page.getByRole('button', { name: 'Confirmar desactivación' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Ficha guardada correctamente.' })).toBeVisible();
  await page.goto(`/app/${business}/trabajadores`);
  await page.getByLabel('Estado del trabajador', { exact: true }).selectOption('false');
  await expect(page.getByText('Mateo Fuentes', { exact: true })).toBeVisible();
  await expect(page.getByText('Valentina Rojas', { exact: true })).toHaveCount(0);
});
test('portal del trabajador en móvil con solicitudes y teclado', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await login(page, 'employee_design');
  await expect(page.getByText('TU PRÓXIMO TURNO', { exact: true })).toBeVisible();
  const nextShift = page.locator('section').filter({ has: page.getByText('TU PRÓXIMO TURNO', { exact: true }) });
  await expect(nextShift.getByText(/09:00.*17:00/)).toBeVisible();
  await expect(page.getByRole('status').filter({ hasText: 'Consultando' })).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'Necesitan tu atención' })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/v2-worker-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Abrir menú' }).click();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Abrir menú' })).toBeFocused();
  await page.getByRole('link', { name: 'Solicitar permiso', exact: true }).first().click();
  await expect(page.getByRole('dialog')).toContainText('Solicitar permiso');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
});
