import { test, expect, type Page } from '@playwright/test';
test.skip(process.env.E2E_PORTAL !== '1', 'Fixture aislada del portal');
const business = process.env.E2E_BUSINESS_A!;
const other = process.env.E2E_BUSINESS_B!;
async function login(page: Page) {
  await page.goto('/iniciar-sesion');
  await page.getByLabel('Nombre de usuario', { exact: true }).fill('worker_portal');
  await page.getByLabel('Contraseña', { exact: true }).fill('Browser-test!pass-9274');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await expect(page).toHaveURL(/\/app(?:\/[^/]+)?$/);
  if (new URL(page.url()).pathname !== '/app') await page.goto('/app');
  await page.goto(`/app/${business}`);
  await expect(page.getByRole('heading', { name: 'Hola, Clara' })).toBeVisible();
}
test('recorrido personal a 320px: turno nocturno, perfil, permiso y autorización', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await login(page);
  const nav = page.getByRole('navigation', { name: 'Navegación del trabajador' });
  await expect(nav.getByRole('link', { name: 'Inicio', exact: true })).toHaveAttribute('aria-current', 'page');
  await expect(page.getByText('Turno nocturno de prueba', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/portal-home-320.png', fullPage: true });
  await page.getByRole('link', { name: 'Ver mi turno', exact: true }).click();
  await page.getByRole('button', { name: /Clara Portal, 23:00/ }).first().click();
  await expect(page.getByRole('dialog')).toContainText('Detalle del turno');
  await expect(page.getByRole('dialog')).toContainText('Turno nocturno de prueba');
  await expect(page.getByRole('button', { name: 'Editar turno', exact: true })).toHaveCount(0);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Semana siguiente' }).click();
  await page.getByRole('button', { name: 'Semana anterior' }).click();
  await expect(page.getByRole('button', { name: /Clara Portal, 23:00/ }).first()).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/portal-shifts-320.png', fullPage: true });
  await nav.getByRole('link', { name: 'Mi perfil', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Clara Portal' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Información personal' })).toBeVisible();
  await expect(page.getByText('+56 9 1234 5678', { exact: true })).toBeVisible();
  await expect(page.getByText('Secreto interno')).toHaveCount(0);
  await expect(page.getByRole('status').filter({ hasText: 'Consultando' })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/portal-profile-320.png', fullPage: true });
  await nav.getByRole('link', { name: 'Permisos', exact: true }).click();
  await page.getByRole('button', { name: 'Solicitar permiso', exact: true }).click();
  await page.getByLabel('Fecha inicial', { exact: true }).fill('2027-02-10');
  await page.getByLabel('Fecha final', { exact: true }).fill('2027-02-10');
  await page.getByLabel('Motivo (opcional)').fill('Observación del trabajador de prueba');
  await page.getByRole('button', { name: 'Enviar solicitud' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: /Ver solicitud de.*2027-02-10/ }).click();
  await expect(page.getByRole('dialog')).toContainText('Pendiente');
  await expect(page.getByRole('dialog')).toContainText('Observación del trabajador de prueba');
  await expect(page.getByRole('button', { name: 'Aprobar', exact: true })).toHaveCount(0);
  await page.keyboard.press('Escape');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/portal-requests-320.png', fullPage: true });
  const base = `/api/v1/businesses/${business}`;
  expect((await page.request.get(`${base}/employees/${process.env.E2E_COLLEAGUE}/`)).status()).toBe(404);
  const { csrfToken } = await (await page.request.get('/api/v1/auth/csrf/')).json();
  const headers = { 'X-CSRFToken': csrfToken };
  expect((await page.request.patch(`${base}/employees/${process.env.E2E_EMPLOYEE}/`, { headers, data: { access_role: 'OWNER' } })).status()).toBe(403);
  expect((await page.request.post(`${base}/shifts/`, { headers, data: {} })).status()).toBe(403);
  await page.goto(`/app/${business}/trabajadores/nuevo`);
  await expect(page.getByRole('heading', { name: 'Acceso restringido', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Registrar trabajador', exact: true })).toHaveCount(0);
});
test('cambio de negocio, carga, error recuperable y adaptación desktop', async ({ page }) => {
  await login(page);
  await page.screenshot({ path: 'test-results/portal-home-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 834, height: 1112 });
  await page.screenshot({ path: 'test-results/portal-home-tablet.png', fullPage: true });
  await page.getByRole('button', { name: 'Abrir menú' }).click();
  await page.getByLabel('Negocio activo').selectOption(other);
  await expect(page.getByRole('heading', { name: 'Tu espacio de trabajo' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Sin próximos turnos programados' })).toBeVisible();
  await expect(page.getByText('Turno nocturno de prueba', { exact: true })).toHaveCount(0);
  await expect(page.getByRole('link', { name: 'Solicitar permiso', exact: true })).toHaveCount(0);
  await page.getByRole('navigation', { name: 'Navegación del trabajador' }).getByRole('link', { name: 'Mi perfil' }).click();
  await expect(page.getByText(/Aún no tienes una ficha vinculada/)).toBeVisible();
  await page.route('**/dashboard/?*', route => route.fulfill({ status: 503, json: { detail: 'Error temporal de prueba' } }));
  await page.goto(`/app/${business}`);
  await expect(page.locator('main').getByRole('alert')).toContainText('Error temporal de prueba');
  await page.unroute('**/dashboard/?*');
  let release!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  await page.route('**/dashboard/?*', async route => { await gate; await route.continue(); });
  await page.getByRole('button', { name: 'Volver a intentar' }).click();
  await expect(page.getByRole('status')).toContainText('Consultando tu planificación');
  release();
  await expect(page.getByRole('heading', { name: 'Hola, Clara' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
