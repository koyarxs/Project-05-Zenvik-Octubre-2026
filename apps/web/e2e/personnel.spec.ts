import { test, expect, type Page } from '@playwright/test';
test.skip(!process.env.E2E_PERSONNEL, 'Uses isolated personnel fixtures');
const business = process.env.E2E_BUSINESS_A!;
const employee = process.env.E2E_EMPLOYEE!;
const root = `/app/${business}`;
async function login(page: Page, username: string) {
  await page.goto('/iniciar-sesion');
  await page.getByLabel('Nombre de usuario', { exact: true }).fill(username);
  await page.getByLabel('Contraseña', { exact: true }).fill('Browser-test!pass-9274');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await expect(page).toHaveURL(/\/app$/);
}

test('OWNER registra, filtra cargos, vincula, suspende y reactiva acceso con auditoría', async ({ page }) => {
  await login(page, 'owner_personnel');
  await page.goto(`${root}/trabajadores/nuevo`);
  await page.getByLabel('Nombre', { exact: true }).fill('Elena');
  await page.getByLabel('Apellido', { exact: true }).fill('Prueba');
  await page.getByLabel('Cargo laboral (opcional)').fill('Encargada de apertura');
  await page.getByLabel('Código interno (opcional)').fill('E-10');
  await page.getByLabel('Teléfono (opcional)').fill('+56 9 2222 3333');
  await page.getByLabel('Jornada o distribución (opcional)').fill('Distribución acordada');
  await page.getByLabel('Observaciones administrativas (opcional)').fill('Nota privada del perfil');
  await page.getByRole('button', { name: 'Registrar trabajador', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Elena Prueba', exact: true })).toBeVisible();
  const profile = page.url();
  await page.getByRole('button', { name: 'Gestionar acceso' }).click();
  await page.getByLabel('Cuenta del negocio').selectOption({ label: 'unlinked_personnel' });
  await page.getByRole('button', { name: 'Confirmar cambio de acceso' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByText('unlinked_personnel', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Gestionar acceso' }).click();
  await page.getByLabel('Acceso habilitado al negocio').uncheck();
  await page.getByRole('button', { name: 'Confirmar cambio de acceso' }).click();
  await expect(page.getByText('Suspendido', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Gestionar acceso' }).click();
  await page.getByLabel('Acceso habilitado al negocio').check();
  await page.getByLabel('Rol de acceso', { exact: true }).selectOption('ADMIN');
  await page.getByRole('button', { name: 'Confirmar cambio de acceso' }).click();
  await expect(page.getByText('Habilitado', { exact: true })).toBeVisible();
  await page.getByText('Historial de cambios del trabajador', { exact: true }).click();
  await expect(page.getByText('Cambio de acceso', { exact: true })).toHaveCount(3);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/personnel-profile-desktop.png', fullPage: true, animations: 'disabled' });
  await page.goto(`${root}/trabajadores`);
  await page.getByLabel('Filtrar por cargo').selectOption('Encargada de apertura');
  await expect(page.getByRole('link', { name: 'Ver ficha de Elena Prueba' })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Ver ficha de Clara Test' })).toHaveCount(0);
  await page.getByLabel('Ordenar trabajadores').selectOption('-name');
  await expect(page.getByRole('link', { name: 'Ver ficha de Elena Prueba' })).toBeVisible();
  await page.screenshot({ path: 'test-results/personnel-directory-desktop.png', fullPage: true, animations: 'disabled' });
  await page.goto(profile);
  await page.getByRole('link', { name: 'Editar trabajador', exact: true }).click();
  await page.getByLabel('Trabajador activo').uncheck();
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('0 turnos programados');
  await page.getByRole('button', { name: 'Confirmar desactivación' }).click();
  await expect(page.getByText('Inactivo', { exact: true }).first()).toBeVisible();
  await expect(page.getByText('Habilitado', { exact: true })).toBeVisible();
});

test('ADMIN edita ficha, trabajador consulta sin notas privadas y ausencia aprobada aparece en turnos', async ({ page, browser }) => {
  await login(page, 'admin_personnel');
  await page.goto(`${root}/trabajadores/${employee}/editar`);
  await page.getByLabel('Teléfono (opcional)').fill('+56 9 8888 7777');
  await page.getByLabel('Cargo laboral (opcional)').fill('Encargada de turno');
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click();
  // The same value also exists in the collapsed audit history. Assert the visible profile.
  await expect(page.getByRole('definition').filter({ hasText: '+56 9 8888 7777' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Gestionar acceso' })).toHaveCount(0);
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, baseURL: 'http://127.0.0.1:3100' });
  const worker = await context.newPage();
  await login(worker, 'worker_personnel');
  await worker.goto(`${root}/trabajadores/${employee}`);
  await expect(worker.getByRole('heading', { name: 'Clara Test', exact: true })).toBeVisible();
  await expect(worker.getByText('Nota reservada del equipo')).toHaveCount(0);
  await expect(worker.getByRole('link', { name: 'Editar trabajador', exact: true })).toHaveCount(0);
  expect(await worker.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await worker.screenshot({ path: 'test-results/personnel-worker-mobile.png', fullPage: true, animations: 'disabled' });
  const csrf = await (await worker.request.get('/api/v1/auth/csrf/')).json();
  expect((await worker.request.patch(`/api/v1/businesses/${business}/employees/${employee}/`, { headers: { 'X-CSRFToken': csrf.csrfToken }, data: { job_title: 'ADMIN' } })).status()).toBe(403);
  expect((await worker.request.get(`/api/v1/businesses/${business}/employees/${process.env.E2E_FOREIGN}/`)).status()).toBe(404);
  await worker.goto(`${root}/permisos`);
  await worker.getByRole('button', { name: 'Solicitar permiso', exact: true }).click();
  await worker.getByLabel('Fecha inicial', { exact: true }).fill('2026-12-10');
  await worker.getByLabel('Fecha final', { exact: true }).fill('2026-12-10');
  await worker.getByLabel('Motivo (opcional)').fill('Trámite solicitado');
  await worker.getByRole('button', { name: 'Enviar solicitud' }).click();
  await expect(worker.getByRole('dialog')).toHaveCount(0);
  await page.goto(`${root}/permisos`);
  await page.getByRole('button', { name: /Ver solicitud de.*2026-12-10/ }).click();
  await expect(page.getByRole('dialog')).toContainText('1 turnos afectados');
  await page.getByRole('button', { name: 'Aprobar', exact: true }).click();
  await page.getByRole('button', { name: 'Confirmar aprobar' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Solicitud aprobada.' })).toBeVisible();
  await page.goto(`${root}/turnos?fecha=2026-12-10`);
  await expect(page.getByText('Permiso aprobado · revisar')).toBeVisible();
  await page.getByRole('button', { name: /Clara Test.*09:00.*13:00/ }).click();
  await page.getByRole('dialog').getByRole('link', { name: 'Clara Test', exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/trabajadores/${employee}$`));
  await page.setViewportSize({ width: 768, height: 1024 });
  await page.goto(`${root}/trabajadores`);
  await expect(page.getByRole('link', { name: 'Ver ficha de Clara Test' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/personnel-directory-tablet.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/personnel-directory-mobile.png', fullPage: true, animations: 'disabled' });
  await context.close();
});
