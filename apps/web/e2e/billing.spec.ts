import { test, expect, type Page } from '@playwright/test';
test.skip(process.env.E2E_BILLING !== '1', 'Fixture aislada de facturación');
async function login(page: Page, username: string) {
  await page.goto('/iniciar-sesion');
  await page.getByLabel('Nombre de usuario', { exact: true }).fill(username);
  await page.getByLabel('Contraseña', { exact: true }).fill('Browser-test!pass-9274');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await expect(page).toHaveURL(/\/app(?:\/[^/]+)?$/);
  if (new URL(page.url()).pathname !== '/app') await page.goto('/app');
}
test('catálogo, alta de negocio, checkout simulado, confirmación, cuota y aislamiento a 320 px', async ({ page, browser }) => {
  test.setTimeout(90000);
  await page.goto('/planes');
  const card = page.locator('article').filter({ has: page.getByRole('heading', { name: 'Plan sintético E2E', exact: true }) });
  await expect(card).toBeVisible();
  await page.screenshot({ path: 'test-results/stage15-plans-desktop.png', fullPage: true });
  await card.getByRole('link', { name: 'Revisar en mi negocio' }).click();
  await login(page, 'billing_owner');
  await page.getByRole('link', { name: 'Registrar mi primer negocio', exact: true }).click();
  await page.getByLabel('Nombre comercial', { exact: true }).fill('Negocio sintético nuevo');
  await page.getByRole('button', { name: 'Registrar negocio', exact: true }).click();
  await expect(page).toHaveURL(/\/app\/[^/]+\/suscripcion$/);
  const business = page.url().split('/').at(-2)!;
  const apiBase = `/api/v1/businesses/${business}`;
  await expect(page.getByRole('heading', { name: 'Mi suscripción', exact: true })).toBeVisible();
  await page.locator('article').filter({ has: page.getByRole('heading', { name: 'Plan sintético E2E', exact: true }) }).getByRole('button', { name: 'Revisar plan mensual' }).click();
  await expect(page.getByRole('dialog')).toContainText('Negocio sintético nuevo');
  await page.route('https://sandbox.flow.cl/**', route => route.fulfill({ contentType: 'text/html', body: '<h1>Proveedor simulado de pruebas</h1>' }));
  const orderResponse = page.waitForResponse(r => r.request().method() === 'POST' && r.url().includes('/billing/checkout') && r.status() === 201);
  await page.getByRole('button', { name: 'Continuar a Flow sandbox' }).click();
  expect((await orderResponse).status()).toBe(201);
  await expect(page.getByRole('heading', { name: 'Proveedor simulado de pruebas' })).toBeVisible();
  const order = { order_id: new URL(page.url()).searchParams.get('token')! };
  expect(order.order_id).toMatch(/^[0-9a-f-]{36}$/);
  const callback = await page.request.post('/api/v1/billing/flow/callback', { form: { token: order.order_id } });
  expect(callback.status()).toBe(200);
  expect((await page.request.post('/api/v1/billing/flow/callback', { form: { token: order.order_id } })).status()).toBe(200);
  await page.setViewportSize({ width: 320, height: 740 });
  await page.goto(`/app/${business}/suscripcion`);
  await expect(page.getByRole('heading', { name: 'Plan sintético E2E', exact: true }).first()).toBeVisible();
  await expect(page.getByText('Confirmado', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/stage15-subscription-320.png', fullPage: true });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  const csrf = await (await page.request.get('/api/v1/auth/csrf')).json();
  const headers = { 'X-CSRFToken': csrf.csrfToken, Origin: 'http://127.0.0.1:3100' };
  expect((await page.request.post(`${apiBase}/employees`, { data: { first_name: 'Primera', last_name: 'Sintética' }, headers })).status()).toBe(201);
  expect((await page.request.post(`${apiBase}/employees`, { data: { first_name: 'Segunda', last_name: 'Sintética' }, headers })).status()).toBe(403);
  expect((await page.request.get(`/api/v1/businesses/${process.env.E2E_BUSINESS_B}/billing`)).status()).toBe(404);
  const workerContext = await browser.newContext();
  const worker = await workerContext.newPage();
  await login(worker, 'billing_worker');
  await worker.goto(`/app/${business}/suscripcion`);
  await expect(worker.getByRole('heading', { name: 'Acceso restringido' })).toBeVisible();
  const workerCsrf = await (await worker.request.get('/api/v1/auth/csrf')).json();
  expect((await worker.request.post(`${apiBase}/billing/changes`, { data: { action: 'CANCEL', request_id: crypto.randomUUID(), expected_revision: 1 }, headers: { 'X-CSRFToken': workerCsrf.csrfToken, Origin: 'http://127.0.0.1:3100' } })).status()).toBe(403);
  await workerContext.close();
});
